def _layer(layer):
    info = {"class": type(layer).__name__, "description": layer.description, "folder": layer.folder,
            "prefix": getattr(layer, "prefix", None), "native_res": layer.native_res,
            "processing": layer.processing, "ttl_days": layer.ttl_days,
            "credit": layer.credit.data if layer.credit else None, "shift": layer.shift}
    if isinstance(layer, src.WcsTiles):
        info.update(url=layer.url, coverage=layer.coverage, crs=layer.crs, axes=layer.axes, fmt=layer.fmt,
                    fetch_res=layer.fetch_res, tile_px=layer.tile_px)
    if isinstance(layer, src.IndexedTiles):
        info.update(index_url=layer.index_url)
    if isinstance(layer, WmsrTiles):
        info.update(url=layer.url, layer=layer.reader.layer, crs=layer.crs, fetch_res=layer.fetch_res,
                    tile_m=layer.tile_m, origin=layer.origin)
    if isinstance(layer, src.ImageServerTiles):
        info.update(url=layer.url, crs=layer.crs, tile_px=layer.tile_px, origin=layer.origin)
        if layer.zones:
            info.update(zones=layer.zones)
    if isinstance(layer, src.GeoWcsTiles):
        info.update(url=layer.url, coverage=layer.coverage, crs=layer.crs, tile_px=layer.tile_px,
                    corner=layer.index.corner, pixel=layer.index.pixel, size=layer.index.size)
    if isinstance(layer, src.GeoSheetTiles):
        info.update(crs=layer.crs, cell=layer.index.cell, origin=layer.index.origin, within=layer.index.within)
    if isinstance(layer, src.InegiSheets):
        info.update(mod=layer.index.mod, index_url=layer.index.index_url, url_prefix=layer.index.url_prefix,
                    cell=layer.index.cell, top=layer.index.top, sheet_ttl=layer.index.ttl_days)
    if isinstance(layer, src.FileBlocks) and (layer.reader.warp is not None or layer.reader.ranged):
        info.update(warp=layer.reader.warp.name if layer.reader.warp is not None else None,
                    ranged=layer.reader.ranged)
    if isinstance(layer, src.MetricSheetTiles):
        info.update(crs=layer.crs, tile_m=layer.tile_m, not_found=layer.reader.not_found)
    if isinstance(layer, src.LercTiles):
        info.update(url=layer.url, max_level=layer.max_level, floor=layer.floor, extent=layer.index.extent)
    if isinstance(layer, src.ZipSheetTiles):
        info.update(crs=layer.crs, archives=len(layer.archives), sheets=len(layer.index.sheets))
    if isinstance(layer, CellSheetTiles):
        info.update(crs=layer.crs, cell=layer.cell, origin=layer.index.origin, members=layer.members)
    if isinstance(layer, S3SheetSets):
        info.update(crs=layer.crs, folders=layer.folders_pattern, members=layer.members,
                    levels={k: (t.folder, t.cell, t.origin) for k, t in layer.levels.items()},
                    level_credits={k: (label, c.data) for k, (label, c) in layer.level_credits.items()})
    return info


